MOD_DESC="Pinned third-party Claude Code skills (config/skills.manifest) vendored into app projects"

_manifest() { echo "${ADX_SKILLS_MANIFEST:-$ADX_ROOT/config/skills.manifest}"; }
_cache()    { echo "$ADX_DOWNLOADS/skills-src"; }

# Emit manifest rows as: name repo sha path
_rows() { grep -vE '^\s*(#|$)' "$(_manifest)" | tr -d ' ' | tr '|' ' '; }

# Fetch one repo at one commit into the cache (shallow, by SHA).
_fetch() {
  local repo="$1" sha="$2" dir
  dir="$(_cache)/${repo//\//__}@$sha"
  if [ "$(git -C "$dir" rev-parse -q --verify HEAD 2>/dev/null)" != "$sha" ]; then
    rm -rf "$dir"
    mkdir -p "$dir"
    git -C "$dir" init -q
    git -C "$dir" remote add origin "https://github.com/$repo.git"
    git -C "$dir" fetch -q --depth 1 origin "$sha"
    git -C "$dir" checkout -q FETCH_HEAD
  fi
  echo "$dir"
}

# Skill profiles kept in the repo, e.g. the project's flat dark diagram style.
# shortcut: only diagram-design has profiles; generalise the target dir if another skill adds them.
_profiles_src() { echo "$ADX_ROOT/config/skill-profiles/diagram-design"; }
_profiles_dst() { echo "$HOME/.diagram-design/profiles"; }

mod_status() {
  local rc=0 name repo sha path f
  while read -r name repo sha path; do
    if [ -d "$(_cache)/${repo//\//__}@$sha/$path" ]; then
      echo "cached  $name ($repo@${sha:0:12})"
    else
      echo "missing $name ($repo@${sha:0:12})"; rc=1
    fi
  done < <(_rows)
  for f in "$(_profiles_src)"/*.md; do
    if cmp -s "$f" "$(_profiles_dst)/$(basename "$f")"; then echo "profile $(basename "$f" .md): installed"
    else echo "profile $(basename "$f" .md): missing or changed (adx skills install)"; rc=1; fi
  done
  return $rc
}

# Pre-fetch every skill in the manifest into the cache.
mod_install() {
  local name repo sha path
  while read -r name repo sha path; do
    adx_log "fetching $name"
    _fetch "$repo" "$sha" >/dev/null
  done < <(_rows)
  mkdir -p "$(_profiles_dst)"
  local f d
  for f in "$(_profiles_src)"/*.md; do
    d="$(_profiles_dst)/$(basename "$f")"
    if [ -f "$d" ] && ! cmp -s "$f" "$d"; then cp "$d" "$d.bak"; adx_warn "kept your edited $(basename "$d") as $d.bak"; fi
    cp "$f" "$d"
  done
  adx_log "installed skill profiles into $(_profiles_dst)"
}

# Vendor skills into <dir>/.claude/skills/ and write a lock file:
#   adx skills apply <project-dir>
mod_apply() {
  local dir="${1:?usage: adx skills apply <project-dir>}" dest lock src name repo sha path
  dest="$dir/.claude/skills"; lock="$dest/SKILLS.lock"
  mkdir -p "$dest"
  printf '# Generated by adx skills apply — do not edit; change config/skills.manifest.\n' > "$lock"
  while read -r name repo sha path; do
    src="$(_fetch "$repo" "$sha")"
    [ -f "$src/$path/SKILL.md" ] || adx_die "$name: no SKILL.md at $repo/$path"
    rm -rf "${dest:?}/$name"
    cp -r "$src/$path" "$dest/$name"
    [ -f "$dest/$name/LICENSE" ] || cp "$src/LICENSE" "$dest/$name/LICENSE" 2>/dev/null || true
    printf '%s %s %s %s\n' "$name" "$repo" "$sha" "$path" >> "$lock"
    adx_log "installed skill $name"
  done < <(_rows)
  adx_log "skills vendored into $dest (lock: $lock)"
}

mod_list() { _rows | awk '{printf "%-16s %s@%s\n", $1, $2, substr($3,1,12)}'; }
